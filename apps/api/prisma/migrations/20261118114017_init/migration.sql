-- Fulltextové vyhledávání bez ohledu na diakritiku.
-- unaccent() není IMMUTABLE, proto ji obalíme funkcí s pevným slovníkem,
-- kterou lze použít v generovaném sloupci i v indexu.
CREATE EXTENSION IF NOT EXISTS "unaccent";

CREATE OR REPLACE FUNCTION teamflow_unaccent(text)
RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $func$ SELECT public.unaccent('public.unaccent'::regdictionary, $1) $func$;

